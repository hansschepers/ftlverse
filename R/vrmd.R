    if (doX) vrmd(section = as.list(setNames("[X]", closerTag)), sectionLevel = 3, doTabbed = 3)
    return("chapter set")
  }
  
  
  if (!is.null(section)){
    section <- as.list(section)
    if(!inherits(section, "list")){
      return("(sub)section must be a list")
    }
    sectionModifier <- paste0(' {-#',names(section),'}')
    
    if (doTabbed == 0){
      tabColorChangeRmdAfter <- character(0)
      tabColorChangeRmd <- character(0)
      sectionModifier <- character(0) 
    } else {
      tabColorChangeRmdAfter <- character(0)
      tabColorChangeRmd <- character(0)
