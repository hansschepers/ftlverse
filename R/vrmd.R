    if (regexpr(chunkBase, chunkId)[1] < 0){
      chunkId <- paste0(chunkBase, chunkId)
    }
  }
  
  # if (grepl("off", do)){
  #   message("disabling vrmd")
  #   vrmd <<- function(do, ...) {
  #     if (grepl("info", do)){
  #       # ftlPlot :: vrmd("info")
  #       message("vrmd is paused!!")
  #     }
  #     if (grepl("on", do)){
  #       message("vrmd re-instated")
  #       if ("ftlPlot" %in% loadedNamespaces()){
  #         # vrmd <<- ftlPlot :: vrmd
  #       } else {
  #         return("vrmd source not found")
  #       }
  #       return(invisible(0))
  #     } else {
  #       message("vrmd is already off")
  #     }
  #     return(invisible(0))
  #   }
  #   return(invisible(0))
  # }
  # if (grepl("on", do)){
  #   message("vrmd is already on")
  # }
  
  if (substr(scriptPackage, 1, 4) != "aph-"){
    scriptPackage <- paste0("aph-", scriptPackage)
  }
  # githubPath <- "https://github.platforms.engineering/DigitalHorticulture/"
  
  # deRuiterStyle
  tabColors <- ftlPalette()
  # tabColors <- c("blue", "red", "green", "orange", "yellow")
  
  if (inherits(chunkCaption, "Date")) chunkCaption <- as.character(chunkCaption)
  if (inherits(tableId,      "Date")) tableId      <- as.character(tableId)
  if (inherits(chunkId,      "Date")) chunkId      <- as.character(chunkId)
  
  if (!is.null(chunkTitle)){
    if (is.null(chunkId)){
      chunkId <- chunkTitle
