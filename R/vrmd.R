    # chunkCaption <- chunkTitle
  }
  if (chartClassAdded[1] == "pggs") {
    chartClassAdded <- make.names3(chunkId)
    log_trace("chartClassAdded {chartClassAdded}")
  }
  
  if (doTabbed == 0 & exists("g.doTabbed", envir = .GlobalEnv)){
    doTabbed <- g.doTabbed
  }
  do <- tolower(do)
  if (tolower(headerData$reportAuthor) == "Hans Schepers") {
    headerData$reportAuthor <- "Hans.Schepers@gmail.com"
  }
  # if (tolower(headerData$reportAuthor) == "gkmsz") {
  #   headerData$reportAuthor <- "Farshad.Goldoust@bayer.com"
  # }
  # if (tolower(headerData$reportAuthor) == "tdoes1") {
  #   headerData$reportAuthor <- "Timo.Doeswijk@bayer.com"
  # }
  # Sys.getenv("PLOTLY_MATHJAX_PATH")
  if (exists("g.repId")){
    if (repId == "global"){
      repId <- g.repId
      log_trace("using report name {repId}")
    } 
  }
  
  log_trace("repId: {repId}, chunkId: {chunkId}")
  log_trace("tempdir: { tmpdir}, {my_temp_file}")
  if (!dir.exists(tmpdir)) {
    log_warn("tempdir not found: { tmpdir}, but dir has been created!")
    dir.create(tmpdir, recursive = TRUE)
    # tmpdir <- tempdir()
    my_temp_file = file.path(tmpdir, paste0(make.names3(chunkId), ".png"))
    log_warn("my_temp_file now: {my_temp_file}")
  }
  
  #zzz
  if (doTabbed == 0){
    tabColorChangeRmdAfter <- character(0)
    tabColorChangeRmd <- character(0)
    sectionModifier <- character(0)
  } else {
    tabColorChangeRmd      <- aphTabColorCss(tabColors[sectionLevel-1])
    tabColorChangeRmdAfter <- aphTabColorCss(tabColors[sectionLevel])
    # cat(tabColorChangeRmd)
    sectionModifier <- paste0(' {.tabset .tabset-fade .tabset-pills ', tabbedSectionModifier, '}')
  }
  
  
  if (is.null(chunkCaption)) {
    # chunkCaption <- chunkId  # 20220729
    if (grepl("dfg", do)) chunkCaption <- tableId
  }
  
  # if (!exists("g.addRmd")) {
  #   g.addRmd = F
  #   g.addRmd <<- g.addRmd
  # }
  # # log_info("g.addRmd ", g.addRmd)
  # if (!g.addRmd) return(invisible(NULL))
  if (!dir.exists(tmpdir)) dir.create(tmpdir, recursive = TRUE)
  
  if (nchar(chunkPrefix) == 0){
    chunkSectionModifier <- character(0)
  }
  
  # write Rmd file to disk
  writeRmd <- function(myGlobalRmd
                       , ffrmd = myGlobalRmd$ffrmd  # [[repId]] ?
                       , exclude = c("ffrmd", "output_file", "tmpdir"
                                     , "renderResult", "headerData")
  ){
    toInclude <- setdiff(names(myGlobalRmd), exclude)  #[[repId]] TODO 20241014
    str(toInclude)
    cat(unlist(myGlobalRmd[toInclude]), file = ffrmd)
  }
  
  
  # if (!exists("script")) {doscript=FALSE ; script = " "}
  if (is.null(script)) {doscript=FALSE ; script = " "}
  
  # init for myGlobalRmd[[repId]]
  if (!exists("g.repId")) {
    g.repId <- "nonExistenT"  # NOT with <<- ! so not exported
    
  }
  
  if (grepl("help", do)){
    help(vrmd)
    return(res)
  }
  
  ############################################### INIT #########################
  if (grepl("init", do) & ((repId == "global") | (repId == g.repId))){
    message("please choose a new meaningful repId")
    return(NULL)
  }
  
  
  
  if (grepl("info", do)){
    # print(ls(pattern = "myGlobalRmd|^g\\.", envir = .GlobalEnv))
    gDotObjects <- ls(pattern = "^g\\.", envir = .GlobalEnv)
    gDotObjects <- intersect(gDotObjects, c("g.addppt", "g.addRmd", "g.doplot", "g.ggly", "g.repId"))
    print(unlist(mget(gDotObjects, envir = .GlobalEnv)))
    
    if (exists("myGlobalRmd")) {
      # repId <- names(myGlobalRmd)[1]
      message("reportId's: ", paste(names(myGlobalRmd), collapse = " | "))
      
      if (repId %in% names(myGlobalRmd)){
        
        if (!quiet) print(strList(myGlobalRmd[[repId]]))
        if (grepl("infoheader", do)) {
          if (all(c("headerData", "ffrmd") %in% names(myGlobalRmd[[repId]]))){
            print(myGlobalRmd[[repId]]$headerData)
            print(myGlobalRmd[[repId]]$ffrmd)
          } else {
            message("no header and rmd file name")
          }
        }
        return(as.data.frame(strList(myGlobalRmd[[repId]])))
        
      } else {
        
        nn <- length(myGlobalRmd)
        print(glue::glue("there are {nn} reports:"))
        print(names(myGlobalRmd))
        print(glue::glue("suggestion: \nvrmd(\"info\", repId = \"{names(myGlobalRmd)[1]}\")"))
        return(as.data.frame(strList(myGlobalRmd)))
      }
      
    } else {
      
      return("no object myGlobalRmd")
      # help(vrmd)
    }
  }
  
  
  
  if (grepl("init", do) | (!exists("myGlobalRmd")) ) {
    if (grepl("clean", do) | !exists("myGlobalRmd")) {
      if (exists("myGlobalRmd")) {
        log_warn("making backup of myGlobalRmd  as myGlobalRmd2 ...")
        myGlobalRmd2 <<- myGlobalRmd
      } #else {
      message("forcing init")
      log_warn("Initializing new !! Global !! Rmd list object (myGlobalRmd)...")
      do <- paste0(do, "init")
      myGlobalRmd <- list()
      #}
      # message("vrmd non initialized yet, please use 'vrmdQuick(<repId>)' first")
      # return("errror")
    }
  }
  
  
  if (grepl("init", do) ) {
    {
      sectionNumberingRow <- paste0('    number_sections: '
                                    , ifelse(sectionNumbering, 'true', 'false'))
      outputHeaderRow <- switch(tolower(outputStyle)
                                , blank = NULL
                                , gv = NULL
                                , pres     = "output: ioslides"
                                , ioslides = "output: ioslides"
                                # , deruiterstyle = "output: deRuiterStyle :: html_report"
                                , word = paste0('output:\n    word_document:'
                                                , '\n      reference_docx: !expr system.file(package = "aphReporting", "msWordTemplates", "wordStylesReference01.docx")'
                                                , '\n      toc: true\n      toc_depth: 2\n      number_sections: true')
                                # default
                                , paste0("output:\n  html_document:\n", sectionNumberingRow)
      )
      
      
      header <- paste0(
        '---
title: "`r headerData$reportTitle`"
subtitle: "`r headerData$reportSubtitle`"
author: "`r headerData$reportAuthor`"
date: "',format(Sys.Date(), "%B %d, %Y") ,'"\n',
        outputHeaderRow, '\n',
        '---\n'
        # , aphTabColorCss(tabColors[1])
        , '\n\n'
      )
      
      
      meta <- paste("made by", userName, getwd())
      {
        openingChunk <- paste0('
```{r setup, include=FALSE}
knitr::opts_chunk$set(echo = FALSE)\n\
```\n\n<!-- ********************* ', meta,' --> \n\n')
      }
    }
    
    
    myGlobalRmd[[repId]] <- list(ffrmd = ffrmd
                                 , output_file = output_file
                                 , tmpdir = tmpdir
                                 , renderResult = FALSE
                                 , headerData = headerData
                                 , header = header
                                 , openingChunk = openingChunk
    )
    # bibliography: "`r system.file('templates', 'r.bib', package = 'deRuiterStyle')`"
    log_info("initialized myGlobalRmd and put in .GlobalEnv")
    myGlobalRmd <<- myGlobalRmd
    res <- c(res, "init done")
    if (isTRUE(insideUI)) return(NULL)
  }
  
  
  if (length(togglePairs)){
    buttons <- character(0)
    buttons <- paste0('<button onclick="aphJsToggle()">', names(togglePairs)[1],'</button>')
    myGlobalRmd[[repId]][paste0("button_", names(togglePairs)[1])] <- paste0('\n\n', buttons, '\n\n')
    res <- c(res, "buttons set")
    # }
    # if (length(togglePairs)){
    toggleStyleScript <- paste0(
      '\n\n<script> function aphJsToggle() {  '
      , 'var x = document.getElementById("', togglePairs[[1]][1],'");'
      , 'var x2 = document.getElementById("', togglePairs[[1]][2],'");'
      , '\nif (x2.style.display === "block") {    x2.style.display = "none";  } else {    x2.style.display = "block";  }'
      , '\nif (x.style.display === "none") {    x.style.display = "block";  } else {    x.style.display = "none";  }'
      , '\n}'
      # hide second element, outside the aphJsToggle() function
      , '\nvar x3 = document.getElementById("', togglePairs[[1]][2],'"); x3.style.display = "block"; '
      , '\n</script>\n\n')
    # cat(toggleStyleScript)
    
    myGlobalRmd[[repId]][names(togglePairs)[1]] <- paste0('\n\n', toggleStyleScript, '\n\n')
    res <- c(res, "togglePairs has been set")
  }
  
  
  
  ############################################### SECTION ######################
  if (length(chapter)){
    # chapter <- "1. CLIMATE"
    sectionTag <- paste0("autoChapter_", chapter)
    closerTag <- paste0("autoCloser_", chapter)
    
    # if (F){
    #   if (is.null(i18n)){
    #     i18n <- starti18n(lang.oi = "nl")
    #     i18n$dict <- data.table::as.data.table(
    #       add2Dict(i18n$dict, list(c(en = "climate", nl = "KLIMAAT")))
    #     )
    #     # grep("climate", i18n$dict$en, ignore.case = TRUE, value = TRUE)
    #   }
    #   
    #   # tail(i18n$dict)
    #   prefix   <- sub("([0-9\\. :-_]*) (.*)", "\\1", chapter)
