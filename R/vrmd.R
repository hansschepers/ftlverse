      log_warn("already restarted the myGlobalRmd[[repId]]")
    }
    res <- c(res, "did a restart")
  }
  
  
  if (grepl("script", do)){
    # system.file(scriptDir, package = scriptPackage)
    # system.file(scriptDir, script, package = scriptPackage)
    ffr <- system.file(scriptDir, script, package = scriptPackage)
    log_info("checking existence of script {ffr} in package: {ffr} {file.exists(ffr)}")
    if (file.exists(ffr)) {
      # script <- sub(.libPaths(), "", ffr)
      ffr <- paste0(githubPath, scriptPackage,"/tree/main/inst")
      ffr <- file.path(ffr, scriptDir, script)
      log_info("linking to script location on Github: {ffr}")
      myGlobalRmd[[repId]]$headerData$reportSubtitle <- 
