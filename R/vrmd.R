  }
  
  
  ############################################### RESTART ######################
  if (grepl("restart", do)){
    if (is.numeric(restartFrom)){
      indexOpening <- restartFrom
    } else {
      indexOpening <- which(restartFrom == names(myGlobalRmd[[repId]]))[1]
