    } else {
      message("file not found: ", ffr)
      myGlobalRmd[[repId]]$headerData$reportSubtitle <- 
        paste0("script: ", script)
    }
    myGlobalRmd <<- myGlobalRmd
    res <- c(res, "added script")
  }
  
  
  if (grepl("docufun", do) & !is.null(docuFun)){
    log_info("documenting key function extract {docuFun}" )
    
    if (file.exists(docuFun)){
      # a script
      ffr <- docuFun
    } else {
      # a function
      FUN <- match.fun(sub("Sim$", "", docuFun))
      ffr <- utils::getSrcFilename(FUN, full.names = TRUE)
    }
    ffr <- sub("~/aphDH", githubPath, ffr)
    # ffr <- sub("/inst/",  "/blob/main/inst/", ffr)
    ffr <- sub("^inst/",  paste0(githubPath, scriptPackage,"/blob/main/inst/"), ffr)
    ffr <- sub("^(\\.\\./)(.*/)(inst/)",  paste0(githubPath, "\\2", "blob/main/inst/"), ffr)
    ffr <- sub("^(\\.\\./)(.*/)(R/)",     paste0(githubPath, "\\2", "tree/main/R/"), ffr)
    ffr <- sub("^R/",  paste0(githubPath, scriptPackage, "/tree/main/R/"), ffr)
    log_trace("ffr: {ffr}")
    if (!length(ffr)) {
      log_error("no meaningful docufun filename found..")
    }
    if (grepl("^https", ffr)) {
      # ffr <- sub("/R/", "/tree/main/R/", ffr)
      log_info("linking to file location on Github: {ffr}")
    } else {
      ffr <- paste0("file:///", ffr)
      log_info("linking to file location on disk: {ffr}")
    }
    log_debug(ffr)
    
    if (showCode){
      textFromFile <- 
        extractSourceCodeHighlight(docuFun
                                   , showComments = showComments
                                   , keepRoxygen = keepRoxygen
                                   , toCiteStart = toCiteStart
                                   , toCiteEnd = toCiteEnd
                                   , prepForLatex = prepForLatex
                                   , dropLatexDrop = dropLatexDrop
        )
      textFromFile <- paste(textFromFile, collapse = "\n")
    } else {
      textFromFile <- ""
    }
    # textFromFile <<- .textFromFile
    .textFromFile <<- textFromFile
    if (prepForLatex){
      # rmdLatexFile <- NULL
      # docuFun <- "test"
      # docuFun <- modelId
      if (is.null(rmdLatexFile)){
        ffrmdbase <- paste0(docuFun
                            , gsub("[# .-]", "", toCiteStart)
                            , gsub("[# .-]", "", toCiteEnd)
                            , ".Rmd")
        rmdLatexFile <- file.path(cacheDir, ffrmdbase)
        if (file.exists(rmdLatexFile)){
          log_warn("making copy before overwriting {rmdLatexFile}")
          ww <- file.copy(rmdLatexFile, paste0(rmdLatexFile, ".b"), overwrite = TRUE)
        }
        log_warn("(over)writing {rmdLatexFile}")
        writeLines(textFromFile, rmdLatexFile)
      }
      child <- paste0(
        "used: [", docuFun, "](", ffr,")"
        ,"\n\n```{r child = "
        , '"',rmdLatexFile,'"'
        , ", out.width = \"1400px\""
        , "}"
        ,'\n\n```\n\n'
      )
      if (log_threshold() >= 450){
        print(child)
      }
      log_trace("*******************************")
    } else {
      child <- paste0(
        "used: [", docuFun, "](", ffr,")",
        "\n\n```{r results = FALSE, eval=FALSE, echo = TRUE}\n",
        textFromFile
        ,'\n```\n\n'
      )
    }
    
    chunkSection <- NULL
    tabbedPrefix <- ""
    if (doTabbed > 0){
      hashes <- paste0(rep("#", doTabbed), collapse = "")
      tabbedPrefix <- paste0("\n\n", hashes, " ", chunkId, "\n\n")
      chunkSection <- paste0(tabbedPrefix)#, '\n\n',chunkPrefix,' ', chunkId, chunkSectionModifier, '\n\n')
    }
    
    
    # myGlobalRmd[[repId]][docuFun] <- child
    # myGlobalRmd[[repId]][gsub("/", "", docuFun)] <- child
    myGlobalRmd[[repId]][make.names3(paste(
      docuFun
      , "Latex"
      , 0+prepForLatex
      , toCiteStart))] <- paste(chunkSection, child)
