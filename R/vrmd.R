cleanVRMD <- function(cachedir = getCacheDir() # "ReportsVRMD"
                      , full.names = TRUE
                      , pattern = "(.*\\.png$)|(.*[\\._=].*\\.Rmd$)", ...){
  ff <- list.files(cachedir
                   , full.names = full.names
                   , pattern = pattern
                   , ...)
